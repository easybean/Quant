// Run from repository root using the existing Playwright/Chromium installation.
const { chromium } = require('/Users/douw/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const out = 'docs/acceptance/2026-09-18-stock-pool'
;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: '/Users/douw/Library/Caches/ms-playwright/chromium-1169/chrome-mac/Chromium.app/Contents/MacOS/Chromium' })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  const api = 'http://192.168.1.132:8511/api/v1'
  const name = '[目录对接验收20260918] TSLA+AAPL '+Date.now()
  async function nav(group, child) { await page.getByRole('button', { name: group, exact: true }).click(); await page.getByRole('button', { name: child, exact: true }).click(); await page.getByRole('heading', { name: child, level: 1, exact: true }).waitFor() }
  async function search(symbol) { await page.getByRole('textbox', { name: '搜索自动证券档案' }).fill(symbol); const response = page.waitForResponse(r => r.url().includes('/security-catalogue?') && r.url().includes('query='+symbol)); await page.getByRole('button', { name: '搜索', exact: true }).click(); await response }
  await page.goto('http://192.168.1.132:8510/')
  assert.equal(await page.getByRole('button', { name: '收益分析', exact: true }).count(), 0)
  await nav('研究工具', '研究股票池')
  await page.getByRole('button', { name: '创建研究股票池', exact: true }).click()
  assert(await page.locator('#asset-pool-name-error').isVisible())
  await page.locator('#asset-pool-name').fill(name)
  await page.locator('#asset-pool-purpose').fill('仅验证目录引用与策略版本锁定，不授予研究资格。')
  await search('TSLA')
  await page.locator('.asset-pool-catalogue-member').filter({ hasText: /^TSLA ·/ }).first().getByRole('checkbox').check()
  await search('AAPL')
  await page.locator('.asset-pool-catalogue-member').filter({ hasText: /^AAPL ·/ }).first().getByRole('checkbox').check()
  await page.getByRole('button', { name: '创建研究股票池', exact: true }).click()
  await page.getByRole('status').filter({ hasText: '已保存' }).waitFor()
  let pools = await (await page.request.get(api+'/asset-pool-drafts')).json()
  const pool = pools.items.find(item => item.name === name)
  assert(pool); assert.equal(pool.instruments.length, 2)
  assert.deepEqual(pool.instruments.map(r => r.record_snapshot.symbol).sort(), ['AAPL', 'TSLA'])
  for (const member of pool.instruments) { assert.equal(member.member_type, 'security_catalogue_v1'); assert.equal(member.record_snapshot.research_qualified, false); assert.equal(member.source_checksum.length, 64) }
  await page.screenshot({ path: out+'/pool.png', fullPage: true })
  await nav('策略配置', '我的策略')
  await page.locator('#visual-strategy-name').fill('[目录对接验收20260918] 固定名单策略')
  await page.locator('#visual-strategy-pool').selectOption(pool.id+'@1')
  const strategyResponse = page.waitForResponse(r => r.url().endsWith('/visual-strategy-drafts') && r.request().method()==='POST')
  await page.getByRole('button', { name: '保存策略定义', exact: true }).click()
  const response = await strategyResponse; assert.equal(response.status(), 201)
  const strategy = await response.json()
  assert.equal(strategy.definition.asset_pool.asset_pool_version, 1)
  const saveV2 = await page.request.put(api+'/asset-pool-drafts/'+pool.id, { data: { name, purpose: '仅验收新版本，旧策略继续锁定v1。', instruments: pool.instruments.map(r => ({ member_type: r.member_type, catalog_id: r.catalog_id, source_checksum: r.source_checksum })) } })
  assert.equal(saveV2.status(), 200)
  const latestStrategies = await (await page.request.get(api+'/visual-strategy-drafts')).json()
  assert.equal(latestStrategies.items.find(r => r.id===strategy.id).definition.asset_pool.asset_pool_version, 1)
  await nav('行情与资料', '数据覆盖与质量')
  await page.getByRole('heading', { name: '每日数据同步进度', exact: true }).waitFor()
  const sync = await (await page.request.get(api+'/us-daily-sync-status')).json(); assert(sync.available); assert.equal(sync.research_qualified, false)
  await page.screenshot({ path: out+'/sync.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  const backtest = await (await page.request.get(api+'/backtests/availability')).json()
  assert.equal(errors.length, 0, errors.join('\n'))
  fs.writeFileSync(out+'/results.json', JSON.stringify({ passed: true, pool_id: pool.id, strategy_id: strategy.id, pool_version_after: 2, strategy_pool_version: 1, sync, backtest, page_errors: errors }, null, 2))
  await browser.close(); console.log('PASS catalogue search → two-stock pool → fixed strategy reference; sync panel; default menu; mobile; no page errors')
})().catch(error => { console.error(error); process.exit(1) })
