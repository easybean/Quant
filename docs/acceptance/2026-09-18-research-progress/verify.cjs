// Read-only acceptance of deployed synthetic reports and acquisition evidence.
const { chromium } = require('/Users/douw/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const output = __dirname
;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: '/Users/douw/Library/Caches/ms-playwright/chromium-1169/chrome-mac/Chromium.app/Contents/MacOS/Chromium' })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  const response = await page.request.get('http://192.168.1.132:8511/api/v1/backtests/reports')
  assert.equal(response.status(), 200)
  const reports = (await response.json()).items.filter(item => item.available)
  assert(reports.length >= 2, 'deployed reports need two actual published artifacts')
  const report = await page.request.get(`http://192.168.1.132:8511/api/v1/backtests/reports/${reports[0].job_id}`)
  const payload = await report.json(); assert.equal(report.status(), 200)
  assert.equal(payload.artifact.report_hash_verified, true)
  assert(payload.contract.bars_sha256.length === 64)
  const compared = await page.request.get(`http://192.168.1.132:8511/api/v1/backtests/reports/compare?left_job_id=${reports[0].job_id}&right_job_id=${reports[0].job_id}`)
  assert.equal((await compared.json()).differences.total_pnl, '0')
  assert.equal((await page.request.get('http://192.168.1.132:8511/api/v1/backtests/reports/invalid')).status(), 404)
  await page.goto('http://192.168.1.132:8510/')
  await page.getByRole('button', { name: '历史回测', exact: true }).click()
  await page.getByRole('button', { name: '回测报告', exact: true }).click()
  await page.getByText('合成验收 · 非真实回测', { exact: true }).waitFor()
  await page.getByText('报告哈希已核验', { exact: true }).waitFor()
  await page.screenshot({ path: path.join(output, 'report.png'), fullPage: true })
  await page.getByRole('button', { name: '结果对比', exact: true }).click()
  await page.locator('.comparison-picker select').nth(1).selectOption(reports[0].job_id)
  await page.getByRole('heading', { name: '终值账本差异（B − A）', exact: true }).waitFor()
  await page.screenshot({ path: path.join(output, 'compare.png'), fullPage: true })
  const detailRoute = /\/api\/v1\/backtests\/reports\/[0-9a-f-]+$/
  await page.route(detailRoute, route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"detail":"acceptance temporary failure"}' }))
  await page.getByRole('button', { name: '回测报告', exact: true }).click()
  await page.getByText('无法读取回测报告', { exact: true }).waitFor()
  await page.unroute(detailRoute)
  await page.getByRole('button', { name: '重新读取', exact: true }).click()
  await page.getByText('报告哈希已核验', { exact: true }).waitFor()
  await page.setViewportSize({ width: 390, height: 844 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  assert.deepEqual(errors, [])
  fs.writeFileSync(path.join(output, 'results.json'), JSON.stringify({ reports: reports.length, report_job: reports[0].job_id, api_read: 'passed', same_input_compare: 'passed', invalid_id: 'passed', desktop_report: 'passed', desktop_compare: 'passed', failure_retry: 'passed', mobile_no_overflow: 'passed', pageErrors: errors }, null, 2))
  await browser.close(); console.log('PASS reports, compare, invalid ID, mobile and no page errors')
})().catch(error => { console.error(error); process.exit(1) })
