// Read-only acceptance of actual deployed acquisition and browser consumption.
const { chromium } = require('/Users/douw/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: '/Users/douw/Library/Caches/ms-playwright/chromium-1169/chrome-mac/Chromium.app/Contents/MacOS/Chromium' })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  const status = await page.request.get('http://192.168.1.132:8511/api/v1/us-daily-sync-status')
  assert.equal(status.status(), 200)
  const summary = await status.json()
  assert(summary.providers.some(row => row.provider === 'massive' && row.success + (row.skipped || 0) === 12139))
  const search = await page.request.get('http://192.168.1.132:8511/api/v1/market-data/us-daily/search?query=ZTS')
  const items = (await search.json()).items.filter(item => item.symbol === 'ZTS')
  assert.equal(items.length, 1)
  assert.equal(items[0].last_date, '2026-09-17')
  const bars = await page.request.get(`http://192.168.1.132:8511/api/v1/market-data/us-daily/bars?series_id=${encodeURIComponent(items[0].series_id)}&start=2026-09-17&end=2026-09-17`)
  assert.equal(bars.status(), 200)
  const payload = await bars.json(); assert.equal(payload.returned_rows, 1)
  await page.goto('http://192.168.1.132:8510/')
  await page.getByRole('button', { name: '行情与资料', exact: true }).click()
  await page.getByRole('button', { name: '数据覆盖与质量', exact: true }).click()
  await page.getByText('Massive 全市场日线', { exact: true }).waitFor()
  await page.screenshot({ path: path.join(__dirname, 'sync.png'), fullPage: true })
  await page.getByRole('button', { name: '行情浏览', exact: true }).click()
  await page.getByRole('textbox', { name: '搜索证券代码（必填）', exact: true }).fill('ZTS')
  await page.getByRole('button', { name: '搜索行情', exact: true }).click()
  await page.locator('.quote-panel h2').filter({ hasText: 'ZTS' }).waitFor()
  assert.equal(await page.locator('.quote-series button').filter({ has: page.locator('strong', { hasText: /^ZTS$/ }) }).count(), 1)
  await page.getByRole('button', { name: '周线', exact: true }).click()
  await page.getByRole('button', { name: '月线', exact: true }).click()
  await page.getByRole('button', { name: '日线', exact: true }).click()
  assert.deepEqual(errors, [])
  const aliasResponse = await page.request.get('http://192.168.1.132:8511/api/v1/market-data/us-daily/search?query=ABR%24D')
  assert.equal(aliasResponse.status(), 200)
  const aliasItems = (await aliasResponse.json()).items.filter(item => item.symbol === 'ABR$D')
  assert.equal(aliasItems.length, 1)
  assert.equal(aliasItems[0].last_date, '2026-09-17')
  await page.getByRole('textbox', { name: '搜索证券代码（必填）', exact: true }).fill('ABR$D')
  await page.getByRole('button', { name: '搜索行情', exact: true }).click()
  await page.locator('.quote-panel h2').filter({ hasText: 'ABR$D' }).waitFor()
  assert.equal(await page.locator('.quote-series button').filter({ has: page.locator('strong', { hasText: /^ABR\$D$/ }) }).count(), 1)
  assert.deepEqual(errors, [])
  fs.writeFileSync(path.join(__dirname, 'results.json'), JSON.stringify({ status: 'passed', symbol: 'ZTS', last_date: items[0].last_date, source: payload.source, one_symbol_result: true, intervals: 'passed', pageErrors: errors }, null, 2))
  await browser.close(); console.log('PASS real daily browser and Massive sync summary')
})().catch(error => { console.error(error); process.exit(1) })
