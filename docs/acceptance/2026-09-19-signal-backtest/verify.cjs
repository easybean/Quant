const {chromium}=require('/Users/douw/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const assert=require('node:assert/strict'),fs=require('node:fs')
;(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:'/Users/douw/Library/Caches/ms-playwright/chromium-1169/chrome-mac/Chromium.app/Contents/MacOS/Chromium'})
 const page=await browser.newPage({viewport:{width:1440,height:1100}})
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('http://192.168.1.132:8510/')
 await page.getByRole('button',{name:'历史回测',exact:true}).click()
 await page.getByRole('button',{name:'新建回测',exact:true}).click()
 await page.getByRole('button',{name:/策略驱动闭环验收/}).click()
 const panel=page.getByRole('region',{name:'策略驱动闭环验收'})
 await panel.getByRole('button',{name:'运行策略闭环验收'}).click()
 await panel.getByRole('alert').waitFor()
 assert.equal(await page.evaluate(()=>document.activeElement.id),'signal-ack')
 await page.locator('#signal-ack').check()
 const jobs=[],reports=[]
 for(const template of ['买入持有基准','双均线策略（2 / 3）']){
  await panel.getByRole('button',{name:template,exact:true}).click()
  const posted=page.waitForResponse(r=>r.url().endsWith('/api/v1/jobs')&&r.request().method()==='POST')
  await panel.getByRole('button',{name:'运行策略闭环验收'}).click()
  const response=await posted;assert.equal(response.status(),202);const {job}=await response.json();jobs.push(job.id)
  await panel.getByText('策略闭环任务已发布',{exact:true}).waitFor({timeout:30000})
  const result=await page.request.get(`http://192.168.1.132:8511/api/v1/backtests/reports/${job.id}`);assert.equal(result.status(),200);reports.push(await result.json())
 }
 assert.notEqual(reports[0].metrics.total_pnl,reports[1].metrics.total_pnl)
 assert.notDeepEqual(reports[0].fills,reports[1].fills)
 const compared=await (await page.request.get(`http://192.168.1.132:8511/api/v1/backtests/reports/compare?left_job_id=${jobs[0]}&right_job_id=${jobs[1]}`)).json();assert(compared.comparable)
 await page.getByRole('button',{name:'回测报告',exact:true}).click()
 await page.getByRole('heading',{name:'每日净值（策略驱动）',exact:true}).waitFor()
 await page.getByRole('heading',{name:'收盘信号与次日订单',exact:true}).waitFor()
 await page.setViewportSize({width:390,height:844})
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 const availability=await (await page.request.get('http://192.168.1.132:8511/api/v1/backtests/availability')).json();assert.equal(availability.formal_backtest_available,false)
 assert.deepEqual(errors,[])
 fs.writeFileSync(`${__dirname}/results.json`,JSON.stringify({jobs,metrics:reports.map(r=>r.metrics),fills:reports.map(r=>r.fills),comparison:compared.differences,required_validation:'passed',report_curve:'passed',mobile_no_overflow:'passed',formal_gate:'blocked',pageErrors:errors},null,2))
 await browser.close();console.log('PASS actual strategy submissions, different trades/PnL, report curve, validation, mobile and formal gate')
})().catch(e=>{console.error(e);process.exit(1)})
