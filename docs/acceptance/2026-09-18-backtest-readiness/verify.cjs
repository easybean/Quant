const { chromium } = require('/Users/douw/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
;(async () => {
  const browser = await chromium.launch({headless:true, executablePath:'/Users/douw/Library/Caches/ms-playwright/chromium-1169/chrome-mac/Chromium.app/Contents/MacOS/Chromium'})
  const page = await browser.newPage({viewport:{width:1440,height:1100}})
  const errors=[]; page.on('pageerror',e=>errors.push(e.message))
  await page.goto('http://192.168.1.132:8510/')
  await page.getByRole('button',{name:'历史回测',exact:true}).click()
  await page.getByRole('button',{name:'新建回测',exact:true}).click()
  const panel=page.getByRole('region',{name:'真实回测数据验收'})
  await panel.getByText('历史可用时点（PIT）',{exact:true}).waitFor()
  assert.equal(await panel.locator('.sync-provider-row').count(),7)
  assert((await panel.innerText()).includes('实际60条'))
  assert(await page.getByRole('button',{name:'正式回测受门禁阻断',exact:true}).isDisabled())
  const route='**/api/v1/backtests/data-readiness'
  await page.route(route,r=>r.fulfill({status:503,body:'{}'}))
  await panel.getByRole('button',{name:'刷新数据验收'}).click()
  await panel.getByRole('alert').waitFor()
  await page.unroute(route)
  await panel.getByRole('button',{name:'刷新数据验收'}).click()
  await panel.getByText('历史可用时点（PIT）',{exact:true}).waitFor()
  await page.setViewportSize({width:390,height:844})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  await page.setViewportSize({width:1440,height:1100})
  await page.getByRole('button',{name:/合成验收样例/}).click()
  await page.locator('.wizard-ack button').click()
  const submitted=page.waitForResponse(r=>r.url().includes('/api/v1/jobs') && r.request().method()==='POST')
  await page.getByRole('button',{name:'提交合成验收任务',exact:true}).click()
  const response=await submitted; assert.equal(response.status(),202); const {job}=await response.json(); assert(job.id)
  await page.getByText('验收任务已发布',{exact:true}).waitFor({timeout:30000})
  const report=await (await page.request.get(`http://192.168.1.132:8511/api/v1/backtests/reports/${job.id}`)).json()
  assert.equal(report.versions.engine.runner_invoked,false)
  assert.equal(report.versions.engine.version,'reference-accounting-v1')
  assert.equal(report.artifact.report_hash_verified,true)
  const items=(await (await page.request.get('http://192.168.1.132:8511/api/v1/backtests/reports')).json()).items
  let legacy=0
  for(const item of items.filter(i=>i.available)) {
    const r=await (await page.request.get(`http://192.168.1.132:8511/api/v1/backtests/reports/${item.job_id}`)).json()
    if(r.versions.engine.execution_implementation==='legacy-unknown') { assert.equal(r.versions.engine.version,'unknown'); assert.equal(r.artifact.report_hash_verified,true); legacy++ }
  }
  assert(legacy>0)
  assert.deepEqual(errors,[])
  fs.writeFileSync(`${__dirname}/results.json`,JSON.stringify({seven_checks:'passed',failure_retry:'passed',mobile_no_overflow:'passed',formal_gate:'blocked',synthetic_job:job.id,new_engine:report.versions.engine,legacy_reports:legacy,pageErrors:errors},null,2))
  await browser.close(); console.log('PASS readiness, retry, mobile, synthetic submission, new/legacy report provenance')
})().catch(e=>{console.error(e);process.exit(1)})
